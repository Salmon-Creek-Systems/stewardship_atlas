"""Seed S3 from the box's on-disk atlases (Phase 3 Step 3 task 8, issue #159).

The one-time move that puts the source of truth in S3. Everything after it —
sessions, publish, the scripts — already assumes the data is there; this is
what puts it there.

**Staging only.** A version used to be a full copy of staging, so the box holds
ten of them for westport alone (6 GB of layers and outlets that are mostly
identical). Carrying that history forward would seed the duplication the
catalog exists to remove, and the history is not lost — it is on the EBS
snapshot, and the first publish after seeding creates the version that matters.

**Derived from config, never from a listing**, for the shared data: only ~20
files in `/root/data` are referenced by any config, and one *unreferenced* file
there is 4.9 GB.

The planners here are pure and take plain paths, so the whole exclusion policy
is testable without S3 or a copy of the box.
"""

